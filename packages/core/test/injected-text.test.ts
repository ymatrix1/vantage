// Synthetic text only. Injected messages are never a request, so never a title (D194).
import { describe, expect, it } from "vitest";
import { firstRequestTitle, looksInjectedTitle, parseTranscriptLine, userRequestText } from "../src/index.ts";

const SID = "11111111-2222-3333-4444-555555555555";
const user = (text: string, extra: Record<string, unknown> = {}): string =>
  JSON.stringify({
    type: "user",
    uuid: `u-${Math.abs(text.length)}`,
    sessionId: SID,
    timestamp: "2026-01-05T09:00:00Z",
    isSidechain: false,
    message: { role: "user", content: text },
    ...extra,
  });
const titleOf = (...texts: string[]): { found: boolean; title: string | null } =>
  firstRequestTitle(
    texts.flatMap((t) => {
      const p = parseTranscriptLine(user(t));
      return p ? [p] : [];
    }),
    SID,
  );

const REAL = "Add pagination to the track page.";
const INJECTED: Record<string, string> = {
  "worktree notice": "You are operating in a git worktree. Run all commands from this directory.",
  "system reminder": "<system-reminder>Codebase and user instructions are shown below.</system-reminder>",
  "unterminated system reminder": "<system-reminder>As you answer the user's questions, use this context",
  "slash command wrapper":
    "<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>",
  "local command output": "<local-command-stdout>Compacted</local-command-stdout>",
  "local command caveat":
    "Caveat: The messages below were generated by the user while running local commands. DO NOT respond.",
  "hook output": "UserPromptSubmit hook additional context: CAVEMAN MODE ACTIVE",
  "task notification": "<task-notification>a background task finished</task-notification>",
  "ci event": '<ci-monitor-event>"Auto-fix" was enabled</ci-monitor-event>',
  interruption: "[Request interrupted by user for tool use]",
  "skill base": "Base directory for this skill: /x/y",
};

describe("injected user messages (D194)", () => {
  for (const [name, text] of Object.entries(INJECTED)) {
    it(`${name} is not a request`, () => {
      expect(userRequestText(text)).toBeNull();
      // The first real message after it titles the session.
      expect(titleOf(text, REAL)).toEqual({ found: true, title: "Add pagination to the track page" });
      // Alone, it leaves nothing to title with and does not stop the search.
      expect(titleOf(text)).toEqual({ found: false, title: null });
    });
  }

  it("cuts leading injected blocks and keeps what the person typed after them", () => {
    const text = `<system-reminder>context</system-reminder>\n<command-name>/x</command-name>\n${REAL}`;
    expect(userRequestText(text)?.trim()).toBe(REAL);
    expect(titleOf(text).title).toBe("Add pagination to the track page");
  });

  it("leaves an ordinary request alone, even one that mentions a tag later", () => {
    expect(userRequestText(REAL)).toBe(REAL);
    expect(userRequestText("Explain what <system-reminder> blocks are")).not.toBeNull();
  });

  it("recognises titles stored before the rule", () => {
    expect(looksInjectedTitle("You are operating in a git worktree")).toBe(true);
    expect(looksInjectedTitle("Caveat: The messages below were generated by the user")).toBe(true);
    expect(looksInjectedTitle("Add pagination to the track page")).toBe(false);
  });
});
